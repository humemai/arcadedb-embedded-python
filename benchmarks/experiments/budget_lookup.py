"""One place that answers: how long may this query run, at this tier?

A budget stops a single slow query so the rest of the cell still reports
(DECISIONS #100, #100a). It used to be one flat constant per lane, which
DECISIONS #106 replaced: cost scales with the corpus, and differently per
query. Measured on mini between SF1 and SF10, a tenfold corpus: whole-graph
aggregations 11x, most-friends 8.9x, a per-seed two-hop 2.4x, a point lookup
1.0x. One number per lane cannot be right for all of them.

`budgets.py` holds the measured table, generated by `derive_budgets.py` from
the bench host's frozen rows. This module is the lookup, and the important
part is what it does when a tier has no measurement yet: it falls back to the
lane's old flat constant AND says so on the row (`<q>_budget_source`), so a
budget that was guessed is never mistaken on the page for one that was
measured. Regenerate the table after a campaign and the guesses disappear.

Never varies by engine. A budget may vary by lane, by tier and by query,
because those are properties of the work; varying it by engine would be
varying the comparison itself.
"""
import os

try:
    from budgets import MEASURED_BUDGETS_S
except ImportError:          # table not generated yet
    MEASURED_BUDGETS_S = {}

MEASURED = "measured"
FALLBACK = "lane default (no measurement at this tier yet)"


# A FALLBACK MUST FIT THE CAP IT RUNS INSIDE. The lane constants were each
# chosen for one query and never multiplied by the number of queries in the
# lane, so the product could exceed the whole-cell cap and censor a cell by
# arithmetic before any engine did anything slow. Read off the documents lane
# on 2026-09-20: five queries, all on the 1,800 s flat default, is 9,000 s
# against a 7,200 s cap -- 125%, so every engine that used its budgets was
# already censored. The graph lane was fine only because its constant happens
# to be 300 s.
#
# So an UNMEASURED query gets at most an equal share of the cell's budget
# envelope. Measured budgets are NOT clamped: they come from the bench host's
# own rows and a cell whose measured budgets exceed its cap is telling you the
# cap is wrong, which is a finding rather than something to paper over.
CAP_SHARE = 0.60   # of the whole-cell cap, left to the queries' iterations;
                   # the rest is ingest, build, first touches and teardown.


def fallback_budget_s(lane, tier, n_queries, lane_default_s):
    """The most an UNMEASURED query may take, given the cap it runs inside."""
    try:
        import runner
        cap = float(runner.TIMEOUT_BY_SCALE[str(tier)])
    except Exception:  # noqa: BLE001
        return float(lane_default_s)
    if not n_queries:
        return float(lane_default_s)
    return min(float(lane_default_s), cap * CAP_SHARE / float(n_queries))


def budget_for(lane, tier, query, default_s, env_var=None, n_queries=None):
    """(seconds, source). `default_s` is the lane's old flat constant.

    An explicit environment override always wins and is labelled as such, so a
    probe run cannot be mistaken for a campaign cell.

    `n_queries` lets an unmeasured query be clamped to its share of the cell
    cap; without it the old flat constant applies unchanged.
    """
    if env_var:
        raw = os.environ.get(env_var)
        if raw:
            try:
                return float(raw), f"override {env_var}={raw}"
            except ValueError:
                pass
    got = MEASURED_BUDGETS_S.get((lane, str(tier), query))
    if got is not None:
        return float(got), MEASURED
    capped = fallback_budget_s(lane, tier, n_queries, default_s)
    if capped < float(default_s):
        return capped, f"{FALLBACK}, clamped to this tier's cap share"
    return float(default_s), FALLBACK


# ---------------------------------------------------------------- abandonment
# THE TAIL MUST NOT DOMINATE THE CAMPAIGN. A budget bounds a query, but an
# engine that cannot finish still burns the whole budget to produce a cell that
# says "did not finish" (2026-09-18: three engines each spent two hours at
# TPC-H SF10 for three censored rows, while the two that could answer took ten
# minutes each). The information in a censored cell does not improve by paying
# for it, so a query whose FIRST touch already shows it cannot complete a
# useful number of iterations is abandoned there, in seconds instead of hours.
#
# The rule is the same for every engine and uses only the engine's own cold
# pass, so it is a property of the work, never of who is running it: if the
# budget cannot buy at least MIN_ITERS iterations at the cold pass's own rate,
# stop. Five, because a p50 over fewer is not a median of anything, and the
# cold pass is the fairest estimator available at that moment.
MIN_ITERS = 5


def abandon(cold_s, budget_s, iterations):
    """(should_abandon, reason). `cold_s` is the first touch, already paid for.

    Returns False when the cold pass is fast enough that the budget buys a
    usable sample, or when the query would finish all its iterations anyway.
    """
    if cold_s <= 0 or budget_s <= 0:
        return False, ""
    affordable = budget_s / cold_s
    if affordable >= min(MIN_ITERS, iterations):
        return False, ""
    return True, (f"abandoned after the cold pass: at {cold_s:.1f} s per "
                  f"iteration the {budget_s:.0f} s budget buys {affordable:.1f} "
                  f"iterations, fewer than the {MIN_ITERS} a median needs")
