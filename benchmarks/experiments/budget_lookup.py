"""One place that answers: how long may this query run, at this tier?

A budget stops a single slow query so the rest of the cell still reports
(DECISIONS #100, #100a). It used to be one flat constant per lane, which
DECISIONS #106 replaced: cost scales with the corpus, and differently per
query. Measured on mini between SF1 and SF10, a tenfold corpus: whole-graph
aggregations 11x, most-friends 8.9x, a per-seed two-hop 2.4x, a point lookup
1.0x. One number per lane cannot be right for all of them.

`budgets.py` holds the measured table, generated by `derive_budgets.py` from
the bench host's frozen rows. This module is the lookup, and the important
part is what it does when a tier has no measurement yet: it falls back to the
lane's old flat constant AND says so on the row (`<q>_budget_source`), so a
budget that was guessed is never mistaken on the page for one that was
measured. Regenerate the table after a campaign and the guesses disappear.

Never varies by engine. A budget may vary by lane, by tier and by query,
because those are properties of the work; varying it by engine would be
varying the comparison itself.
"""
import os

try:
    from budgets import MEASURED_BUDGETS_S
except ImportError:          # table not generated yet
    MEASURED_BUDGETS_S = {}

MEASURED = "measured"
FALLBACK = "lane default (no measurement at this tier yet)"


def budget_for(lane, tier, query, default_s, env_var=None):
    """(seconds, source). `default_s` is the lane's old flat constant.

    An explicit environment override always wins and is labelled as such, so a
    probe run cannot be mistaken for a campaign cell.
    """
    if env_var:
        raw = os.environ.get(env_var)
        if raw:
            try:
                return float(raw), f"override {env_var}={raw}"
            except ValueError:
                pass
    got = MEASURED_BUDGETS_S.get((lane, str(tier), query))
    if got is not None:
        return float(got), MEASURED
    return float(default_s), FALLBACK
