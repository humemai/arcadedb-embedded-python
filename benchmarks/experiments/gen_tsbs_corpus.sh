#!/bin/bash
# Generate the TSBS cpu-only corpus the L4 lane measures.
#
# WHY THIS FILE EXISTS. The 2.59M-point corpus the paper's time-series block
# uses has been sitting on the bench host since 2026-07-22 with NO recorded
# recipe: no script, no README, no note of the scale or the time window. It was
# reconstructible only by reading the data back (100 distinct hostnames, first
# timestamp 2026-01-01T00:00:00Z, last 259,190 s later, 10 s apart, ten tags
# and ten fields), which is how the parameters below were recovered. A corpus
# nobody can regenerate is a result nobody can reproduce, and this lane already
# reports ingest rates against it.
#
# WHICH AXIS SCALES. TSBS calls `--scale` the number of hosts, and that is the
# axis this script varies: cardinality is what a time-series engine's index
# actually strains against, and lengthening the window instead just adds
# samples to series that already exist. Keeping the window and the interval
# fixed also means point count scales exactly with scale, so tiers are
# comparable by construction.
#
#   scale=100   2.59M points   ~0.89 GB   the tier measured in the paper today
#   scale=1000  25.9M points   ~8.97 GB   10x
#   scale=4000  104M points    ~35.9 GB   40x
#
# Verified: scale=1000 produced 25,920,000 lines at 8.97 GB, ten tags and ten
# fields per line, i.e. the same schema as the original at exactly 10.0x.
#
#   ./gen_tsbs_corpus.sh 1000 /path/to/bench-data/tsbs
set -eu
SCALE=${1:-100}
OUT=${2:-$HOME/bench-data/tsbs}
BIN=${TSBS_GEN:-$HOME/go/bin/tsbs_generate_data}

# Pinned so a regenerated corpus is byte-identical, not merely similar. The
# original's seed is unknown (nothing recorded it), so tiers generated by this
# script are self-consistent but will not reproduce the 2026-07-22 file's
# values. Shape, schema and cardinality do match; only the pseudo-random
# measurements differ, and no reported number depends on them.
SEED=${TSBS_SEED:-123}
START=${TSBS_START:-2026-01-01T00:00:00Z}
END=${TSBS_END:-2026-01-04T00:00:00Z}
INTERVAL=${TSBS_INTERVAL:-10s}

[ -x "$BIN" ] || {
  echo "no tsbs_generate_data at $BIN" >&2
  echo "  git clone --depth 1 https://github.com/timescale/tsbs.git" >&2
  echo "  cd tsbs && go build -o $BIN ./cmd/tsbs_generate_data" >&2
  exit 1
}

mkdir -p "$OUT"
DEST="$OUT/cpu_influx_s${SCALE}.lp"
echo "generating scale=$SCALE ($START..$END every $INTERVAL, seed $SEED)"
"$BIN" --use-case=cpu-only --seed="$SEED" --scale="$SCALE" \
       --timestamp-start="$START" --timestamp-end="$END" \
       --log-interval="$INTERVAL" --format=influx > "$DEST"

# Acceptance, because "the file exists" is not the same as "the corpus is
# right": the point count must be scale x intervals exactly, and the schema
# must still be the ten-tag/ten-field one the lane's adapters parse.
python3 - "$DEST" "$SCALE" <<'PY'
import os, subprocess, sys
p, scale = sys.argv[1], int(sys.argv[2])
n = int(subprocess.run(["wc", "-l", p], capture_output=True, text=True).stdout.split()[0])
first = open(p).readline().split(" ")
tags, fields = first[0].count("="), first[1].count("=")
print("  %.2f GB, %d points, %d tags, %d fields" % (os.path.getsize(p) / 1e9, n, tags, fields))
bad = []
if n % scale:
    bad.append("point count %d is not a multiple of scale %d" % (n, scale))
if tags != 10 or fields != 10:
    bad.append("schema is %d tags / %d fields, expected 10/10" % (tags, fields))
if bad:
    sys.exit("REJECT:\n  " + "\n  ".join(bad))
print("  ok: %d intervals per host" % (n // scale))
PY
