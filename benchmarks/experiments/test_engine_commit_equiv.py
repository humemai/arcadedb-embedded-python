"""The release-pair equivalence of the native server image (ENGINE-COMMIT-EQUIV, 26.11.1).

Upstream builds `arcadedata/arcadedb:<release>-native` at the release tag, one version-string commit after the commit of the JVM image, the jars and
both wheels. Every place that compares the server-reported commit to the pin (verify_native_server_image.sh, runner.engine_commit_problems,
arm_identity.server_settings_problems, provenance_check.check_engine_commit_matches_build) accepts that pair only when it is explicitly opted in
and in engine_commit_equiv.json, only for the NATIVE server, only for a release pair. Nothing is started: docker, curl and uv are stubs.
Run with `python -m pytest test_engine_commit_equiv.py -q` from this directory.
"""
import os
import stat
import subprocess
import sys
import textwrap
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
os.environ.setdefault("BENCH_INSTRUMENT", "2026-11")

import arm_identity as AI  # noqa: E402
import engine_pin  # noqa: E402
import provenance_check as PC  # noqa: E402
import runner as R  # noqa: E402

PIN = "a3a5d124572608412aa187f9c4b290e071699473"
EQ = "0f3bb2238c3cfc79c4a1c2cf2d8c5e36489652c0"
OTHER = "deadbeef0" + "0" * 31
VERIFY = HERE / "verify_native_server_image.sh"


# ---- the registry (engine_commit_equiv.json, generated by make_engine_commit_equiv.py from the git diff)
def test_the_registry_names_the_release_pair_and_nothing_else():
    assert engine_pin.native_server_equivalent(EQ, PIN) == "26.11.1"
    assert engine_pin.native_server_equivalent(EQ[:9], PIN[:9]) == "26.11.1"
    assert engine_pin.native_server_equivalent(OTHER, PIN) == ""
    assert engine_pin.native_server_equivalent(EQ, OTHER) == ""            # another pin: a dev pair never gets it
    assert engine_pin.native_server_equivalent(EQ[:6], PIN) == ""          # prefixes under 7 characters never match
    assert engine_pin.native_server_equivalent(EQ, PIN, registry={"26.11.1.dev0": {"pin": PIN, "equivalent": [EQ]}}) == ""   # release keys only
    assert engine_pin.native_server_equivalent(EQ, PIN, registry={}) == ""


def test_the_registry_entry_has_no_non_version_line():
    e = engine_pin._equiv_registry()["26.11.1"]
    assert e["non_version_lines"] == 0 and e["pin"] == PIN and e["equivalent"] == [EQ]


# ---- runner.engine_commit_problems
def test_runner_refuses_the_equivalent_commit_unless_the_pins_opt_in_and_the_registry_agrees():
    assert R.engine_commit_problems(EQ, PIN)                                  # no opt-in: unchanged
    assert R.engine_commit_problems(EQ, PIN, ())
    assert R.engine_commit_problems(EQ, PIN, (EQ[:9],)) == []                 # opted in and in the registry
    assert R.engine_commit_problems(EQ, PIN, (OTHER[:9],))                    # opted in for another commit
    assert R.engine_commit_problems(OTHER, PIN, (OTHER[:9],))                 # opted in but the registry does not know it
    assert R.engine_commit_problems(EQ, OTHER, (EQ[:9],))                     # a different pin (dev pair)
    assert R.engine_commit_problems(PIN[:9], PIN) == [] and R.engine_commit_problems(None, PIN, (EQ,))


# ---- arm_identity.server_settings_problems (the freeze-time pair gate)
def _served_row(build, server_commit):
    return {"lane": "l1", "scale": "small", "workload": "oltp", "backend": "arcadedb_server", "engine_backend": build,
            "engine_version": "server:26.11.1 (build %s/1/UNKNOWN)" % server_commit, "engine_commit": PIN, "server_engine_commit": server_commit,
            "server_settings": {"arcadedb.txWalFlush": "0"}, "server_mode": "development", "server_cpus": 4, "server_max_heap_bytes": 2 << 30}


def _commit_problems(rows):
    return [p for p in AI.server_settings_problems(rows) if "reports engine commit" in p]


def test_freeze_gate_accepts_the_equivalent_commit_on_the_native_server_only():
    assert _commit_problems([_served_row("native", EQ)]) == []
    assert _commit_problems([_served_row("jvm", EQ)])                         # the JVM server must equal the pin
    assert _commit_problems([_served_row("native", OTHER)])
    assert _commit_problems([_served_row("native", PIN)]) == []


# ---- provenance_check.check_engine_commit_matches_build
def _prov_row(build, reported):
    return {"lane": "l5", "scale": "s", "backend": "arcadedb_server", "rep": 1, "engine_commit": PIN, "engine_backend": build,
            "engine_version": "server:26.11.1 (build %s/1/UNKNOWN)" % reported}


def test_provenance_check_accepts_the_equivalent_commit_on_the_native_server_only(capsys):
    assert PC.check_engine_commit_matches_build([_prov_row("native", EQ)]) == 0
    assert PC.check_engine_commit_matches_build([_prov_row("jvm", EQ)]) == 1
    assert PC.check_engine_commit_matches_build([_prov_row("native", OTHER)]) == 1
    capsys.readouterr()


# ---- verify_native_server_image.sh against stubbed docker, curl and uv (no docker, no network, no JVM)
@pytest.fixture()
def stubs(tmp_path):
    bin_ = tmp_path / "bin"
    bin_.mkdir()

    def put(name, body):
        p = bin_ / name
        p.write_text("#!/bin/bash\n" + textwrap.dedent(body))
        p.chmod(p.stat().st_mode | stat.S_IEXEC)

    put("docker", '''
        case "$1" in
          image) exit 0 ;;
          run) echo stubcid ;;
          port) echo 0.0.0.0:49999 ;;
          rm) exit 0 ;;
        esac
        ''')
    put("curl", '''
        case "$*" in
          */api/v1/ready*) exit 0 ;;
          *) printf '{"result":[{"v":"26.11.1 (build %s/1793827332511/UNKNOWN)"}]}' "$STUB_SERVER_SHA" ;;
        esac
        ''')
    # `uv run --no-project python -c CODE`: run CODE with the interpreter that runs this test (no network, no resolver)
    put("uv", f'shift 4\nexec {sys.executable} "$@"\n')
    return bin_


def _verify(stubs, server_sha, *args, equiv=None):
    env = {"PATH": f"{stubs}:{os.environ['PATH']}", "STUB_SERVER_SHA": server_sha, "HOME": os.environ.get("HOME", "/")}
    if equiv is not None:
        env["NATIVE_SERVER_EQUIV_SHAS"] = equiv
    return subprocess.run(["bash", str(VERIFY), "arcadedata/arcadedb:26.11.1-native", *args], capture_output=True, text=True, env=env, timeout=60)


def test_verify_without_the_variable_behaves_as_before(stubs):
    ok = _verify(stubs, PIN, PIN)
    assert ok.returncode == 0 and f"NATIVE_SERVER_COMMIT={PIN}" in ok.stdout and "NATIVE_SERVER_EQUIV" not in ok.stdout
    bad = _verify(stubs, EQ, PIN)
    assert bad.returncode == 1 and "NATIVE SERVER UNVERIFIED: the native server runs 0f3bb2238, expected a3a5d1245" in bad.stdout
    assert "NATIVE_SERVER_EQUIV" not in bad.stdout
    assert _verify(stubs, EQ).returncode == 0                                  # no pin: it only reports


def test_verify_accepts_the_listed_equivalent_and_says_so(stubs):
    r = _verify(stubs, EQ, PIN, equiv=EQ)
    assert r.returncode == 0, r.stdout
    assert f"NATIVE_SERVER_EQUIV={EQ} accepted for pin {PIN}: see ENGINE-COMMIT-EQUIV" in r.stdout
    r = _verify(stubs, EQ, PIN, equiv=f"{OTHER[:12]},{EQ[:9]}")             # comma list, short prefix
    assert r.returncode == 0 and "NATIVE_SERVER_EQUIV=" in r.stdout
    r = _verify(stubs, PIN, PIN, equiv=EQ)                                      # the pin itself needs no equivalence and prints no EQUIV line
    assert r.returncode == 0 and "NATIVE_SERVER_EQUIV" not in r.stdout


def test_verify_refuses_an_unlisted_commit_a_missing_pin_and_a_malformed_entry(stubs):
    r = _verify(stubs, OTHER, PIN, equiv=EQ)
    assert r.returncode == 1 and "NATIVE SERVER UNVERIFIED" in r.stdout and "NATIVE_SERVER_EQUIV=" not in r.stdout
    r = _verify(stubs, EQ, equiv=EQ)                                            # equivalence without the pin
    assert r.returncode == 1 and "only together with the pin" in r.stdout
    r = _verify(stubs, EQ, PIN, equiv="0f3bb2")                                 # under 7 characters
    assert r.returncode == 1 and "not 7 to 40" in r.stdout
    r = _verify(stubs, EQ, PIN, equiv="0F3BB2238C")                             # upper case is not a sha spelling the pins use
    assert r.returncode == 1
    r = _verify(stubs, EQ, PIN, equiv="")                                       # empty variable = no variable
    assert r.returncode == 1 and "NATIVE_SERVER_EQUIV=" not in r.stdout
